//! exFAT volume construction.
//!
//! This builds p1, the media volume WinPE reads. exFAT rather than FAT32 because
//! `install.wim` is over FAT32's 4 GiB per-file limit on every current Windows release:
//! 4.04 GiB on Server 2022, 4.75 GiB on Windows 11 22H2, so it can be copied byte
//! for byte with no WIM tooling, no splitting, and no risk of altering Microsoft's
//! payload. The firmware never reads this partition; it boots the small FAT32 one,
//! which loads a driver for this one.
//!
//! Scope is deliberately narrow. The image is built once and never modified, so every
//! file is allocated contiguously and flagged `NoFatChain`, which means the FAT is
//! never consulted for file data at all. That removes most of the bookkeeping a
//! general-purpose implementation needs.
//!
//! Layout, for the 6 GiB / 128 KiB-cluster case this produces:
//!
//! ```text
//!   sector 0        boot region, 12 sectors, mirrored at sector 12
//!   sector 2048     FAT, 512 sectors
//!   sector 2560     cluster heap; cluster 2 is the allocation bitmap,
//!                   3 the up-case table, 4 the root directory
//! ```
//!
//! Verified two ways: whole-volume against the committed goldens in `testdata/exfat/`,
//! which were generated by the JavaScript builder this was ported from, over a range of
//! configurations; and structure by structure against p1 of an image that installed
//! Windows on real Oxide hardware.

use crate::sparse::SparseImage;
use anyhow::{Result, bail};

/// One definition, shared with the partition table.
const SECTOR: u64 = crate::mbr::SECTOR as u64;

/// Bytes per directory entry.
const ENTRY: usize = 32;

/// The up-case table covers the whole Basic Multilingual Plane.
const UPCASE_ENTRIES: usize = 65536;
const UPCASE_BYTES: usize = UPCASE_ENTRIES * 2;

/// Directory entry type codes.
const E_VOLUME_LABEL: u8 = 0x83;
const E_ALLOCATION_BITMAP: u8 = 0x81;
const E_UPCASE_TABLE: u8 = 0x82;
const E_FILE: u8 = 0x85;
const E_STREAM: u8 = 0xc0;
const E_NAME: u8 = 0xc1;

const ATTR_DIRECTORY: u16 = 0x10;
const ATTR_ARCHIVE: u16 = 0x20;

/// `AllocationPossible | NoFatChain`. The second flag is what says "this file is one
/// contiguous run, do not walk the FAT for it".
const FLAGS_CONTIGUOUS: u8 = 0x03;

/// UTF-16 code units per name entry.
const NAME_CHARS_PER_ENTRY: usize = 15;

/// The boot region is 12 sectors and appears twice: main at sector 0, backup at 12.
const BOOT_REGION_SECTORS: u64 = 12;

/// Where the FAT starts, on a 1 MiB boundary, well clear of both boot regions.
const FAT_OFFSET_SECTORS: u64 = 2048;

/// A directory-entry timestamp, as the single 32-bit field exFAT packs it into.
///
/// No clock and no time zone, for the same reason as [`crate::fat32::Timestamp`]: the
/// builders this was ported from encoded an explicit UTC instant with local-time getters,
/// so every entry in both volumes carried the builder host's zone and no two people
/// produced the same image. Holding the encoded field makes that unrepresentable.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Timestamp(pub u32);

impl Timestamp {
    /// 2020-01-01 00:00:00 — what every image we build is stamped with.
    pub const MEDIA_EPOCH: Self = Self((40 << 25) | (1 << 21) | (1 << 16));

    /// Encode a civil date and time. Seconds have two-second resolution.
    pub fn from_civil(
        year: u16,
        month: u8,
        day: u8,
        hour: u8,
        minute: u8,
        second: u8,
    ) -> Result<Self> {
        if !(1980..=2107).contains(&year) {
            bail!("year {year} is outside exFAT's 1980..=2107 range");
        }
        if !(1..=12).contains(&month) || !(1..=31).contains(&day) {
            bail!("{year}-{month}-{day} is not a date");
        }
        if hour > 23 || minute > 59 || second > 59 {
            bail!("time {hour}:{minute}:{second} is not a time of day");
        }
        Ok(Self(
            (((year - 1980) as u32) << 25)
                | ((month as u32) << 21)
                | ((day as u32) << 16)
                | ((hour as u32) << 11)
                | ((minute as u32) << 5)
                | ((second / 2) as u32),
        ))
    }
}

/// A file whose bytes the caller still has to write, at `offset` in the finished image.
///
/// This is how a 4 GiB `install.wim` gets into the volume without being held in memory
/// alongside the image that contains it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Placement {
    pub path: String,
    pub offset: u64,
    pub size: u64,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Geometry {
    pub total_sectors: u64,
    pub sectors_per_cluster: u32,
    pub sectors_per_cluster_shift: u8,
    pub cluster_bytes: u64,
    pub fat_offset: u32,
    pub fat_length: u32,
    pub cluster_heap_offset: u32,
    pub cluster_count: u32,
}

impl Geometry {
    pub fn capacity_bytes(&self) -> u64 {
        self.cluster_count as u64 * self.cluster_bytes
    }
}

#[derive(Debug, Clone)]
pub struct Options {
    pub size_bytes: u64,
    /// Upper-cased and truncated to 11 characters, as `exfat.js` does.
    pub label: String,
    /// `None` picks by volume size: 128 KiB clusters over 2 GiB, 32 KiB below. Big
    /// clusters keep the FAT and bitmap small, and these volumes hold a handful of
    /// very large files, so internal fragmentation does not matter.
    pub sectors_per_cluster: Option<u32>,
    /// Recorded in the boot sector. Informational — nothing reads it to find the
    /// volume — but wrong values confuse tools that check it.
    pub partition_offset_lba: u64,
    pub volume_serial: u32,
    pub stamp: Timestamp,
}

impl Default for Options {
    fn default() -> Self {
        Self {
            size_bytes: 0,
            label: "OXIDE".to_string(),
            sectors_per_cluster: None,
            partition_offset_lba: 0,
            volume_serial: 0x4f58_4944, // "OXID"
            stamp: Timestamp::MEDIA_EPOCH,
        }
    }
}

impl Options {
    /// The known-good configuration of p1: the media volume WinPE reads.
    pub fn media(sectors: u64, partition_offset_lba: u64) -> Self {
        Self {
            size_bytes: sectors * SECTOR,
            label: "WINSETUP".to_string(),
            partition_offset_lba,
            ..Self::default()
        }
    }
}

struct Node {
    name: String,
    is_dir: bool,
    /// Insertion-ordered, keyed by upper-cased name. The order fixes both entry order
    /// and cluster allocation order, so the volume is only reproducible while it is
    /// stable.
    children: Vec<(String, usize)>,
    data: Option<Vec<u8>>,
    reserved: bool,
    path: String,
    first_cluster: u32,
    cluster_count: u32,
    byte_size: u64,
    /// Directory entries this directory holds, including the three fixed ones if it is
    /// the root. Set by `measure`.
    entry_count: u64,
}

impl Node {
    fn new(name: String, is_dir: bool) -> Self {
        Self {
            name,
            is_dir,
            children: Vec::new(),
            data: None,
            reserved: false,
            path: String::new(),
            first_cluster: 0,
            cluster_count: 0,
            byte_size: 0,
            entry_count: 0,
        }
    }
}

const ROOT: usize = 0;

/// A contiguous cluster run.
#[derive(Debug, Clone, Copy)]
struct Alloc {
    first: u32,
    count: u32,
}

pub struct ExFatBuilder {
    label: String,
    partition_offset_lba: u64,
    volume_serial: u32,
    stamp: Timestamp,
    size_bytes: u64,
    geometry: Geometry,
    nodes: Vec<Node>,
    /// Every run handed out, so the FAT can carry a real chain for each.
    allocations: Vec<Alloc>,
    upcase_checksum: u32,
    placements: Vec<Placement>,
}

impl ExFatBuilder {
    pub fn new(opts: Options) -> Result<Self> {
        if opts.size_bytes == 0 {
            bail!("an exFAT volume needs a size");
        }
        let label: String =
            opts.label.to_uppercase().chars().take(11).collect();

        let shift = match opts.sectors_per_cluster {
            Some(spc) => {
                if !spc.is_power_of_two() {
                    bail!(
                        "sectors per cluster must be a power of two, got {spc}"
                    );
                }
                spc.trailing_zeros() as u8
            }
            // 128 KiB over 2 GiB, 32 KiB below.
            None => {
                if opts.size_bytes > 2 * 1024 * 1024 * 1024 {
                    8
                } else {
                    6
                }
            }
        };
        let geometry = geometry_for(opts.size_bytes, shift)?;

        Ok(Self {
            label,
            partition_offset_lba: opts.partition_offset_lba,
            volume_serial: opts.volume_serial,
            stamp: opts.stamp,
            size_bytes: opts.size_bytes,
            geometry,
            nodes: vec![Node::new(String::new(), true)],
            allocations: Vec::new(),
            upcase_checksum: 0,
            placements: Vec::new(),
        })
    }

    pub fn geometry(&self) -> Geometry {
        self.geometry
    }

    /// Files whose bytes the caller still has to write. Empty until `build`.
    pub fn placements(&self) -> &[Placement] {
        &self.placements
    }

    pub fn add_dir(&mut self, path: &str) -> Result<usize> {
        let mut node = ROOT;
        for part in split_path(path) {
            check_name(part)?;
            let key = part.to_uppercase();
            match self.child(node, &key) {
                Some(existing) => {
                    if !self.nodes[existing].is_dir {
                        bail!(
                            "cannot create directory {path}: {part} is a file"
                        );
                    }
                    node = existing;
                }
                None => {
                    let child = Node::new(part.to_string(), true);
                    let id = self.push(child);
                    self.nodes[node].children.push((key, id));
                    node = id;
                }
            }
        }
        Ok(node)
    }

    pub fn add_file(&mut self, path: &str, data: Vec<u8>) -> Result<()> {
        let size = data.len() as u64;
        self.insert_file(path, size, Some(data), false)
    }

    /// Reserve `size` bytes without supplying them. After `build`, the bytes go at the
    /// matching entry in `placements`.
    pub fn reserve_file(&mut self, path: &str, size: u64) -> Result<()> {
        self.insert_file(path, size, None, true)
    }

    fn insert_file(
        &mut self,
        path: &str,
        size: u64,
        data: Option<Vec<u8>>,
        reserved: bool,
    ) -> Result<()> {
        let mut parts = split_path(path);
        let name = match parts.pop() {
            Some(name) => name,
            None => bail!("a file needs a name, got {path:?}"),
        };
        check_name(name)?;
        let dir = if parts.is_empty() {
            ROOT
        } else {
            self.add_dir(&parts.join("/"))?
        };

        let mut node = Node::new(name.to_string(), false);
        node.data = data;
        node.reserved = reserved;
        node.byte_size = size;
        node.path = if parts.is_empty() {
            format!("/{name}")
        } else {
            format!("/{}/{name}", parts.join("/"))
        };

        let key = name.to_uppercase();
        let id = self.push(node);
        // Last writer wins, in place. A caller overriding `sources/EI.CFG` with
        // `sources/ei.cfg` means one file, not two entries a case-insensitive reader
        // cannot tell apart; replacing in place keeps entry order and so the bytes.
        match self.nodes[dir].children.iter().position(|(k, _)| *k == key) {
            Some(slot) => self.nodes[dir].children[slot] = (key, id),
            None => self.nodes[dir].children.push((key, id)),
        }
        Ok(())
    }

    fn push(&mut self, node: Node) -> usize {
        self.nodes.push(node);
        self.nodes.len() - 1
    }

    fn child(&self, dir: usize, key: &str) -> Option<usize> {
        self.nodes[dir]
            .children
            .iter()
            .find(|(k, _)| k == key)
            .map(|(_, id)| *id)
    }

    fn kids(&self, dir: usize) -> Vec<usize> {
        self.nodes[dir].children.iter().map(|(_, id)| *id).collect()
    }

    pub fn build(&mut self) -> Result<SparseImage> {
        let upcase = upcase_table();
        self.upcase_checksum = checksum32(&upcase);
        self.allocations.clear();
        self.placements.clear();

        let bitmap_bytes = (self.geometry.cluster_count as u64).div_ceil(8);

        // Fixed metadata first, then the tree, all contiguous.
        //
        // Every run is recorded so the FAT can carry a chain for it. Files and
        // subdirectories set NoFatChain and do not strictly need one, but the
        // allocation bitmap, up-case table and root directory have no such flag in
        // their entries — their chains must be in the FAT or the volume will not
        // mount. Writing chains for everything is cheap and keeps the two views
        // consistent.
        let mut next: u32 = 2;
        let bitmap = self.take(&mut next, bitmap_bytes)?;
        let upcase_alloc = self.take(&mut next, UPCASE_BYTES as u64)?;

        self.measure(ROOT, true);
        let root_bytes = self.nodes[ROOT].entry_count * ENTRY as u64;
        let root_alloc = self.take(&mut next, root_bytes)?;
        self.nodes[ROOT].first_cluster = root_alloc.first;
        self.nodes[ROOT].cluster_count = root_alloc.count;

        self.allocate_children(ROOT, &mut next)?;

        let used = next - 2;
        if used > self.geometry.cluster_count {
            bail!(
                "contents need {} but the volume holds {}",
                fmt_bytes(used as u64 * self.geometry.cluster_bytes),
                fmt_bytes(self.geometry.capacity_bytes()),
            );
        }

        let mut image = SparseImage::new(self.size_bytes)?;
        self.write_boot_region(&mut image, 0, &root_alloc)?;
        self.write_boot_region(&mut image, BOOT_REGION_SECTORS, &root_alloc)?;
        self.write_fat(&mut image)?;
        self.write_bitmap(&mut image, &bitmap, used)?;
        image.write(self.cluster_offset(upcase_alloc.first), &upcase)?;
        self.write_dir(
            &mut image,
            ROOT,
            true,
            &bitmap,
            &upcase_alloc,
            bitmap_bytes,
        )?;
        Ok(image)
    }

    /// Hand out a contiguous run big enough for `bytes`, recording it for the FAT.
    ///
    /// Zero bytes still takes one cluster: a directory with no children is still a
    /// directory and needs somewhere to be.
    fn take(&mut self, next: &mut u32, bytes: u64) -> Result<Alloc> {
        let first = *next;
        let count =
            u32::try_from(bytes.div_ceil(self.geometry.cluster_bytes).max(1))
                .map_err(|_| {
                anyhow::anyhow!("allocation of {bytes} bytes is too large")
            })?;
        *next = next
            .checked_add(count)
            .ok_or_else(|| anyhow::anyhow!("cluster numbering overflowed"))?;
        let alloc = Alloc { first, count };
        self.allocations.push(alloc);
        Ok(alloc)
    }

    /// Entry counts, which depend only on names, so this runs before any cluster
    /// exists. exFAT has no `.` or `..`, so a subdirectory counts only its children.
    fn measure(&mut self, dir: usize, is_root: bool) {
        // Volume label, allocation bitmap, up-case table.
        let mut entries: u64 = if is_root { 3 } else { 0 };
        for id in self.kids(dir) {
            let name_entries = self.nodes[id]
                .name
                .chars()
                .count()
                .div_ceil(NAME_CHARS_PER_ENTRY);
            entries += 2 + name_entries as u64;
            if self.nodes[id].is_dir {
                self.measure(id, false);
            }
        }
        self.nodes[dir].entry_count = entries;
    }

    fn allocate_children(&mut self, dir: usize, next: &mut u32) -> Result<()> {
        for id in self.kids(dir) {
            let is_dir = self.nodes[id].is_dir;
            let bytes = if is_dir {
                self.nodes[id].entry_count * ENTRY as u64
            } else {
                self.nodes[id].byte_size
            };
            if !is_dir && self.nodes[id].byte_size == 0 {
                // An empty file names cluster 0 and takes no space at all.
                self.nodes[id].first_cluster = 0;
                self.nodes[id].cluster_count = 0;
            } else {
                let alloc = self.take(next, bytes)?;
                self.nodes[id].first_cluster = alloc.first;
                self.nodes[id].cluster_count = alloc.count;
            }
            if is_dir {
                self.allocate_children(id, next)?;
            }
        }
        Ok(())
    }

    fn cluster_offset(&self, cluster: u32) -> u64 {
        (self.geometry.cluster_heap_offset as u64
            + (cluster as u64 - 2) * self.geometry.sectors_per_cluster as u64)
            * SECTOR
    }

    fn write_boot_region(
        &self,
        image: &mut SparseImage,
        start_sector: u64,
        root: &Alloc,
    ) -> Result<()> {
        let mut boot = [0u8; SECTOR as usize];
        boot[0..3].copy_from_slice(&[0xeb, 0x76, 0x90]);
        boot[3..11].copy_from_slice(b"EXFAT   ");
        put64(&mut boot, 64, self.partition_offset_lba);
        put64(&mut boot, 72, self.geometry.total_sectors);
        put32(&mut boot, 80, self.geometry.fat_offset);
        put32(&mut boot, 84, self.geometry.fat_length);
        put32(&mut boot, 88, self.geometry.cluster_heap_offset);
        put32(&mut boot, 92, self.geometry.cluster_count);
        put32(&mut boot, 96, root.first);
        put32(&mut boot, 100, self.volume_serial);
        put16(&mut boot, 104, 0x0100); // revision 1.00
        put16(&mut boot, 106, 0); // volume flags
        boot[108] = 9; // bytes per sector shift: 512
        boot[109] = self.geometry.sectors_per_cluster_shift;
        boot[110] = 1; // one FAT
        boot[111] = 0x80; // drive select
        boot[112] = 0; // percent in use
        boot[510] = 0x55;
        boot[511] = 0xaa;
        image.write(start_sector * SECTOR, &boot)?;

        // Extended boot sectors 1..=8 are empty but must carry the signature.
        let mut ext = [0u8; SECTOR as usize];
        put32(&mut ext, 508, 0xaa55_0000);
        for i in 1..=8u64 {
            image.write((start_sector + i) * SECTOR, &ext)?;
        }

        // Sector 9 (OEM parameters) and 10 (reserved) stay zero.

        // Sector 11 holds a checksum over the preceding eleven sectors, repeated to
        // fill it. VolumeFlags and PercentInUse are excluded because they change at
        // runtime, and a checksum over a field that moves would invalidate itself.
        let mut region = vec![0u8; 11 * SECTOR as usize];
        region[..SECTOR as usize].copy_from_slice(&boot);
        for i in 1..=8usize {
            let at = i * SECTOR as usize;
            region[at..at + SECTOR as usize].copy_from_slice(&ext);
        }
        let mut sum: u32 = 0;
        for (i, byte) in region.iter().enumerate() {
            if i == 106 || i == 107 || i == 112 {
                continue;
            }
            sum = sum.rotate_right(1).wrapping_add(*byte as u32);
        }
        let mut check = [0u8; SECTOR as usize];
        for i in 0..SECTOR as usize / 4 {
            put32(&mut check, i * 4, sum);
        }
        image.write((start_sector + 11) * SECTOR, &check)?;
        Ok(())
    }

    fn write_fat(&self, image: &mut SparseImage) -> Result<()> {
        let highest = self
            .allocations
            .iter()
            .map(|a| a.first as u64 + a.count as u64)
            .max()
            .unwrap_or(2);
        let mut fat = vec![0u8; highest as usize * 4];
        put32(&mut fat, 0, 0xffff_fff8); // media descriptor
        put32(&mut fat, 4, 0xffff_ffff); // reserved

        for alloc in &self.allocations {
            for i in 0..alloc.count {
                let cluster = alloc.first + i;
                let next = if i == alloc.count - 1 {
                    0xffff_ffff
                } else {
                    cluster + 1
                };
                put32(&mut fat, cluster as usize * 4, next);
            }
        }
        image.write(self.geometry.fat_offset as u64 * SECTOR, &fat)
    }

    fn write_bitmap(
        &self,
        image: &mut SparseImage,
        bitmap: &Alloc,
        used: u32,
    ) -> Result<()> {
        // Only the used prefix is written; the rest of the bitmap is zero, which is
        // what "free" means, so it costs nothing.
        let mut bytes = vec![0u8; ((used as u64).div_ceil(8).max(1)) as usize];
        for i in 0..used as usize {
            bytes[i >> 3] |= 1 << (i & 7);
        }
        image.write(self.cluster_offset(bitmap.first), &bytes)
    }

    fn write_dir(
        &mut self,
        image: &mut SparseImage,
        dir: usize,
        is_root: bool,
        bitmap: &Alloc,
        upcase: &Alloc,
        bitmap_bytes: u64,
    ) -> Result<()> {
        let capacity =
            self.nodes[dir].cluster_count as u64 * self.geometry.cluster_bytes;
        let mut buf = vec![0u8; capacity as usize];
        let mut at = 0usize;

        if is_root {
            let mut label = [0u8; ENTRY];
            label[0] = E_VOLUME_LABEL;
            label[1] = self.label.chars().count() as u8;
            put_utf16(&mut label, 2, &self.label);
            at = put_entry(&mut buf, at, &label)?;

            let mut bm = [0u8; ENTRY];
            bm[0] = E_ALLOCATION_BITMAP;
            bm[1] = 0; // first of one bitmap; a second would set bit 0
            put32(&mut bm, 20, bitmap.first);
            put64(&mut bm, 24, bitmap_bytes);
            at = put_entry(&mut buf, at, &bm)?;

            let mut uc = [0u8; ENTRY];
            uc[0] = E_UPCASE_TABLE;
            put32(&mut uc, 4, self.upcase_checksum);
            put32(&mut uc, 20, upcase.first);
            put64(&mut uc, 24, UPCASE_BYTES as u64);
            at = put_entry(&mut buf, at, &uc)?;
        }

        for id in self.kids(dir) {
            for entry in self.file_entry_set(id) {
                at = put_entry(&mut buf, at, &entry)?;
            }
        }

        let offset = self.cluster_offset(self.nodes[dir].first_cluster);
        image.write(offset, &buf)?;

        for id in self.kids(dir) {
            if self.nodes[id].is_dir {
                self.write_dir(image, id, false, bitmap, upcase, bitmap_bytes)?;
            } else if self.nodes[id].reserved {
                self.placements.push(Placement {
                    path: self.nodes[id].path.clone(),
                    offset: self.cluster_offset(self.nodes[id].first_cluster),
                    size: self.nodes[id].byte_size,
                });
            } else if self.nodes[id].byte_size > 0 {
                let offset = self.cluster_offset(self.nodes[id].first_cluster);
                if let Some(data) = &self.nodes[id].data {
                    image.write(offset, data)?;
                }
            }
        }
        Ok(())
    }

    /// The file entry, its stream extension, and the name entries — one directory
    /// entry set, which is how exFAT represents a single file.
    fn file_entry_set(&self, id: usize) -> Vec<[u8; ENTRY]> {
        let node = &self.nodes[id];
        let chars: Vec<char> = node.name.chars().collect();
        let name_entries = chars.len().div_ceil(NAME_CHARS_PER_ENTRY);
        let size = if node.is_dir {
            node.entry_count * ENTRY as u64
        } else {
            node.byte_size
        };

        let mut file = [0u8; ENTRY];
        file[0] = E_FILE;
        file[1] = 1 + name_entries as u8; // secondary entries following
        put16(
            &mut file,
            4,
            if node.is_dir { ATTR_DIRECTORY } else { ATTR_ARCHIVE },
        );
        put32(&mut file, 8, self.stamp.0); // created
        put32(&mut file, 12, self.stamp.0); // modified
        put32(&mut file, 16, self.stamp.0); // accessed

        let mut stream = [0u8; ENTRY];
        stream[0] = E_STREAM;
        stream[1] = FLAGS_CONTIGUOUS;
        stream[3] = chars.len() as u8;
        put16(&mut stream, 4, name_hash(&node.name));
        put64(&mut stream, 8, size); // valid data length
        put32(&mut stream, 20, node.first_cluster);
        put64(&mut stream, 24, size);

        let mut all = vec![file, stream];
        for i in 0..name_entries {
            let mut e = [0u8; ENTRY];
            e[0] = E_NAME;
            let chunk: String = chars
                .iter()
                .skip(i * NAME_CHARS_PER_ENTRY)
                .take(NAME_CHARS_PER_ENTRY)
                .collect();
            put_utf16(&mut e, 2, &chunk);
            all.push(e);
        }

        // The set checksum spans every entry, skipping its own two bytes. A reader
        // that finds a mismatch treats the whole set as corrupt, so this is the
        // difference between a file being there and the volume looking damaged.
        let mut sum: u16 = 0;
        for (index, byte) in all.iter().flatten().enumerate() {
            if index == 2 || index == 3 {
                continue;
            }
            sum = sum.rotate_right(1).wrapping_add(*byte as u16);
        }
        put16(&mut all[0], 2, sum);
        all
    }
}

fn geometry_for(size_bytes: u64, shift: u8) -> Result<Geometry> {
    if shift > 25 {
        bail!("sectors-per-cluster shift {shift} is out of range");
    }
    let spc = 1u64 << shift;
    let total_sectors = size_bytes / SECTOR;
    if total_sectors <= FAT_OFFSET_SECTORS {
        bail!("a {size_bytes}-byte volume is too small for exFAT");
    }

    // Solve for a cluster count whose FAT and bitmap fit alongside it. The FAT's size
    // depends on the cluster count and the cluster count depends on the FAT's size, so
    // it is estimate-then-correct; at these sizes it converges in one pass.
    let mut cluster_count = (total_sectors - FAT_OFFSET_SECTORS) / spc;
    for _ in 0..4 {
        let fat_sectors = ((cluster_count + 2) * 4).div_ceil(SECTOR);
        let fat_length = align(fat_sectors, spc);
        let heap = FAT_OFFSET_SECTORS + fat_length;
        if heap >= total_sectors {
            bail!("a {size_bytes}-byte volume is too small for exFAT");
        }
        let next = (total_sectors - heap) / spc;
        if next == cluster_count {
            break;
        }
        cluster_count = next;
    }

    let fat_length = align(((cluster_count + 2) * 4).div_ceil(SECTOR), spc);
    let cluster_heap_offset = FAT_OFFSET_SECTORS + fat_length;
    if cluster_count < 16 {
        bail!("volume too small for exFAT: {cluster_count} clusters");
    }
    Ok(Geometry {
        total_sectors,
        sectors_per_cluster: spc as u32,
        sectors_per_cluster_shift: shift,
        cluster_bytes: spc * SECTOR,
        fat_offset: FAT_OFFSET_SECTORS as u32,
        fat_length: u32::try_from(fat_length)
            .map_err(|_| anyhow::anyhow!("FAT is too large to address"))?,
        cluster_heap_offset: u32::try_from(cluster_heap_offset).map_err(
            |_| anyhow::anyhow!("cluster heap is too far into the volume"),
        )?,
        cluster_count: u32::try_from(cluster_count)
            .map_err(|_| anyhow::anyhow!("too many clusters"))?,
    })
}

// --- helpers ------------------------------------------------------------

fn put16(buf: &mut [u8], at: usize, value: u16) {
    buf[at..at + 2].copy_from_slice(&value.to_le_bytes());
}

fn put32(buf: &mut [u8], at: usize, value: u32) {
    buf[at..at + 4].copy_from_slice(&value.to_le_bytes());
}

fn put64(buf: &mut [u8], at: usize, value: u64) {
    buf[at..at + 8].copy_from_slice(&value.to_le_bytes());
}

fn put_entry(buf: &mut [u8], at: usize, entry: &[u8; ENTRY]) -> Result<usize> {
    if at + ENTRY > buf.len() {
        bail!("directory entries overflow the clusters measured for them");
    }
    buf[at..at + ENTRY].copy_from_slice(entry);
    Ok(at + ENTRY)
}

/// Write `s` as UTF-16LE code units at `at`.
fn put_utf16(buf: &mut [u8], at: usize, s: &str) {
    for (i, unit) in s.encode_utf16().enumerate() {
        put16(buf, at + i * 2, unit);
    }
}

fn align(value: u64, to: u64) -> u64 {
    value.div_ceil(to) * to
}

fn split_path(path: &str) -> Vec<&str> {
    path.split(['/', '\\']).filter(|p| !p.is_empty() && *p != ".").collect()
}

/// Names are limited to the Basic Multilingual Plane.
///
/// `exfat.js` writes one 16-bit unit per code point and counts name length in code
/// points, so anything needing a surrogate pair overflows its name entries and throws.
/// Refusing it up front with an explanation beats matching the crash, and nothing on
/// Windows media comes close.
fn check_name(name: &str) -> Result<()> {
    if let Some(c) = name.chars().find(|c| *c as u32 > 0xffff) {
        bail!(
            "{name:?} contains {c:?}, which is outside the range exFAT names are \
             written in here"
        );
    }
    if name.chars().count() > 255 {
        bail!("{name:?} is longer than exFAT's 255-character limit");
    }
    Ok(())
}

/// The up-case table: a Unicode simple-uppercase mapping over the whole BMP.
///
/// Derived rather than embedded, and derived the same way `exfat.js` derives it —
/// take the standard uppercase mapping and keep it only where it maps one character to
/// exactly one character, so `ß` stays `ß` rather than becoming `SS`. Hand-folding
/// ASCII and Latin-1 instead produces a table `fsck_exfat` rejects.
///
/// The table is anchored by its checksum: the test pins it to the value in p1 of an
/// image that booted, so a Unicode data change in either language shows up as a test
/// failure rather than as a volume Windows quietly dislikes.
fn upcase_table() -> Vec<u8> {
    let mut table = vec![0u8; UPCASE_BYTES];
    for code in 0..UPCASE_ENTRIES as u32 {
        let mut up = code as u16;
        // Surrogates have no case mapping and pass through untouched.
        if !(0xd800..=0xdfff).contains(&code) {
            if let Some(c) = char::from_u32(code) {
                let mut upper = c.to_uppercase();
                if let (Some(u), None) = (upper.next(), upper.next()) {
                    if (u as u32) <= 0xffff {
                        up = u as u32 as u16;
                    }
                }
            }
        }
        put16(&mut table, code as usize * 2, up);
    }
    table
}

fn checksum32(bytes: &[u8]) -> u32 {
    let mut sum: u32 = 0;
    for byte in bytes {
        sum = sum.rotate_right(1).wrapping_add(*byte as u32);
    }
    sum
}

/// The name hash stored in the stream extension, so a reader can reject a name without
/// comparing it.
///
/// Note this up-cases by hand — ASCII plus the Latin-1 range — rather than through the
/// up-case table the volume carries, which is what the specification calls for. Only
/// names outside those ranges would hash differently, and every name on Windows media
/// is ASCII. Preserved as `exfat.js` has it so the two engines agree.
fn name_hash(name: &str) -> u16 {
    let mut hash: u16 = 0;
    for ch in name.chars() {
        let mut c = ch as u32 as u16;
        if (0x61..=0x7a).contains(&c) {
            c -= 0x20;
        } else if (0xe0..=0xfe).contains(&c) && c != 0xf7 {
            c -= 0x20;
        }
        hash = hash.rotate_right(1).wrapping_add(c & 0xff);
        hash = hash.rotate_right(1).wrapping_add(c >> 8);
    }
    hash
}

fn fmt_bytes(n: u64) -> String {
    const UNITS: [&str; 4] = ["B", "KiB", "MiB", "GiB"];
    let mut value = n as f64;
    let mut unit = 0;
    while value >= 1024.0 && unit < UNITS.len() - 1 {
        value /= 1024.0;
        unit += 1;
    }
    format!("{value:.1} {}", UNITS[unit])
}

