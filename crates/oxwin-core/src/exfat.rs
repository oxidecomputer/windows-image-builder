    /// Serialise a block stream: offset as u64 LE, length as u32 LE, then the bytes.
    /// This is the encoding the committed goldens were written in, so it is fixed.
    fn encode_blocks(blocks: &[(u64, Vec<u8>)]) -> Vec<u8> {
        let mut out = Vec::new();
        for (offset, data) in blocks {
            out.extend_from_slice(&offset.to_le_bytes());
            out.extend_from_slice(&(data.len() as u32).to_le_bytes());
            out.extend_from_slice(data);
        }
        out
    }

    fn decode_blocks(raw: &[u8]) -> Vec<(u64, Vec<u8>)> {
        let mut blocks = Vec::new();
        let mut at = 0usize;
        while at < raw.len() {
            let offset =
                u64::from_le_bytes(raw[at..at + 8].try_into().unwrap());
            let len =
                u32::from_le_bytes(raw[at + 8..at + 12].try_into().unwrap())
                    as usize;
            at += 12;
            blocks.push((offset, raw[at..at + len].to_vec()));
            at += len;
        }
        blocks
    }

