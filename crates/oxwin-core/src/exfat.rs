    /// 131072 bytes of derived Unicode data, pinned by four bytes from the image that
    /// booted. If Rust's Unicode tables ever move, this is where it shows.
    #[test]
    fn the_upcase_table_is_the_one_that_booted() {
        let table = upcase_table();
        assert_eq!(table.len(), UPCASE_BYTES);
        assert_eq!(checksum32(&table), REFERENCE_UPCASE_CHECKSUM);

        let entry = |c: u32| {
            u16::from_le_bytes([
                table[c as usize * 2],
                table[c as usize * 2 + 1],
            ])
        };
        assert_eq!(entry('a' as u32), 'A' as u16);
        assert_eq!(entry('A' as u32), 'A' as u16);
        assert_eq!(entry('7' as u32), '7' as u16);
        // A mapping that expands to two characters is not a simple mapping, so the
        // character stays as itself.
        assert_eq!(entry(0x00df), 0x00df); // sharp s
        assert_eq!(entry(0xfb01), 0xfb01); // fi ligature
        // A one-to-one mapping outside ASCII is taken.
        assert_eq!(entry(0x00e9), 0x00c9); // é -> É
        assert_eq!(entry(0x0131), 'I' as u16); // dotless i
        // Surrogates have no case mapping and pass through.
        assert_eq!(entry(0xd800), 0xd800);
        assert_eq!(entry(0xdfff), 0xdfff);
    }

