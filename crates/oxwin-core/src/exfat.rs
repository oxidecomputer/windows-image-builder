    #[test]
    fn an_empty_file_names_cluster_zero_and_takes_no_space() {
        let mut b = ExFatBuilder::new(Options::media(MEDIA_SECTORS, MEDIA_LBA))
            .unwrap();
        b.add_file("/empty.txt", Vec::new()).unwrap();
        b.add_file("/after.txt", b"x".to_vec()).unwrap();
        b.build().unwrap();
        let empty = b.child(ROOT, "EMPTY.TXT").unwrap();
        let after = b.child(ROOT, "AFTER.TXT").unwrap();
        assert_eq!(b.nodes[empty].first_cluster, 0);
        // Root is cluster 4, so the next real allocation is 5 — the empty file did not
        // consume it.
        assert_eq!(b.nodes[after].first_cluster, 5);
    }

    /// An empty directory still needs somewhere to be.
    #[test]
    fn an_empty_directory_gets_a_cluster() {
        let mut b = ExFatBuilder::new(Options::media(MEDIA_SECTORS, MEDIA_LBA))
            .unwrap();
        b.add_dir("/empty").unwrap();
        b.build().unwrap();
        let dir = b.child(ROOT, "EMPTY").unwrap();
        assert_eq!(b.nodes[dir].cluster_count, 1);
        assert_eq!(b.nodes[dir].first_cluster, 5);
        // And its directory entry reports zero bytes, because it holds no entries.
        assert_eq!(b.nodes[dir].entry_count, 0);
    }

    /// exFAT has no "." or ".." entries, unlike FAT32. A subdirectory's size counts
    /// only its children, so getting this wrong makes a directory look empty.
    #[test]
    fn a_subdirectory_counts_only_its_children() {
        let mut b = ExFatBuilder::new(Options::media(MEDIA_SECTORS, MEDIA_LBA))
            .unwrap();
        b.add_file("/dir/a.txt", b"a".to_vec()).unwrap();
        b.add_file("/dir/b.txt", b"b".to_vec()).unwrap();
        b.build().unwrap();
        let dir = b.child(ROOT, "DIR").unwrap();
        // Two files, each a file entry, a stream extension and one name entry.
        assert_eq!(b.nodes[dir].entry_count, 6);
        // The root has the three metadata entries plus one three-entry set for "dir".
        assert_eq!(b.nodes[ROOT].entry_count, 6);
    }

