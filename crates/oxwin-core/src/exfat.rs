    #[test]
    fn every_allocation_gets_a_fat_chain() {
        // Files set NoFatChain and do not need one, but the bitmap, up-case table and
        // root directory have no such flag — their chains must be in the FAT or the
        // volume will not mount at all.
        let mut b = ExFatBuilder::new(Options::media(MEDIA_SECTORS, MEDIA_LBA))
            .unwrap();
        b.reserve_file("/big.bin", 400_000).unwrap(); // four clusters
        let image = b.build().unwrap();
        let fat = 2048 * SECTOR;
        let read = |cluster: u32| {
            u32::from_le_bytes(
                image.read(fat + cluster as u64 * 4, 4).try_into().unwrap(),
            )
        };
        assert_eq!(read(0), 0xffff_fff8); // media descriptor
        assert_eq!(read(1), 0xffff_ffff);
        assert_eq!(read(2), 0xffff_ffff); // bitmap, one cluster
        assert_eq!(read(3), 0xffff_ffff); // up-case table, one cluster
        assert_eq!(read(4), 0xffff_ffff); // root directory
        // The file: four clusters chained, then end of chain.
        assert_eq!(read(5), 6);
        assert_eq!(read(6), 7);
        assert_eq!(read(7), 8);
        assert_eq!(read(8), 0xffff_ffff);
    }

