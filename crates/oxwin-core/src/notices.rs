//! This workspace is MPL-2.0, but the image it builds is mostly not ours: virtio guest
//! drivers, Win32-OpenSSH, a UEFI Shell, three filesystem drivers and a chain loader.
//! **Two of those are copyleft** — `uefintfs.efi` is GPL-2.0-or-later and the three
//! `efifs` drivers are GPL-3.0-or-later, being GRUB2-derived — so every release of this
//! tool conveys GPL'd object code and owes the corresponding notices and source.
//!
//! These are standalone UEFI executables, unmodified, loaded and run by firmware in its own
//! context; nothing here links against them or shares data structures with them, so the
//! MPL code stays MPL under GPLv2 §2 / GPLv3 §5 mere aggregation. `build.rs` does
//! `include_bytes!` the whole payload into one binary, see THIRD-PARTY.md.
//!
//! Why the notices live here and not in `payload-manifest.json`, which would otherwise be
//! the natural home:
//!
//! - The manifest is generated by `fetch-payload.sh` into a gitignored `assets/`, so a
//!   fresh clone would have no notices at all and a reader of the repository could not
//!   find the terms.
//! - The manifest is only as present as the payload is. A build with no payload still
//!   ships this table, which is the case where getting it wrong is cheapest and least
//!   noticed.
//! - Adding fields to the manifest would change the embedded payload and therefore the
//!   fingerprint, for a change that carries no bytes onto any volume.
//!
//! The license texts are committed under `licenses/` and `include_str!`d, which is the
//! one exception to the ground rule that third-party files are not committed: that rule
//! exists to keep binaries out of the tree, and a license text is precisely the thing
//! that has to travel with the artifact rather than be fetched by whoever builds it.
//!
//! The versions here are duplicated from `tools/fetch-payload.sh`, so
//! `every_pinned_version_is_accounted_for` reads that script and requires them to agree.
//! One constant in two places has already drifted once in this workspace and skipped the
//! bootstrap script on every install.

/// The terms one payload component is under.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum License {
    /// `uefi-ntfs`. Its `LICENSE.txt` is the GPLv2 text and `boot.c` says "either
    /// version 2 of the License, or (at your option) any later version".
    Gpl2OrLater,
    /// `efifs`, which is GPLv3+ because the drivers are GRUB 2.0 read-only drivers.
    Gpl3OrLater,
    /// EDK2, and therefore the UEFI Shell binary built from it.
    Bsd2ClausePatent,
    /// The virtio-win guest drivers.
    Bsd3Clause,
    /// OpenSSH's own summary file, which is a collection of BSD-and-freer terms rather
    /// than one nameable license.
    OpenSsh,
    /// cloudbase-init itself.
    Apache2,
    /// The CPython runtime bundled inside the cloudbase-init MSI.
    Python,
    /// libarchive's own summary file, as shipped with the bundled `bsdtar.exe`.
    /// Its top matter is a 2-clause BSD grant; see `bsdtar.COPYING`'s own
    /// caveat that per-file statements, not this summary, are controlling.
    Bsd2Clause,
    /// `Elevate.exe`, bundled inside the cloudbase-init MSI with no adjacent
    /// license file of its own. See the `Component` entry for how this was
    /// identified and why LGPL-2.1-or-later, not the upstream repo's MIT
    /// `LICENSE.md`, is the operative text here.
    Lgpl21OrLater,
}

impl License {
    /// The SPDX identifier, or the closest thing to one.
    pub fn spdx(self) -> &'static str {
        match self {
            Self::Gpl2OrLater => "GPL-2.0-or-later",
            Self::Gpl3OrLater => "GPL-3.0-or-later",
            Self::Bsd2ClausePatent => "BSD-2-Clause-Patent",
            Self::Bsd3Clause => "BSD-3-Clause",
            Self::OpenSsh => "OpenSSH (BSD-style, see text)",
            Self::Apache2 => "Apache-2.0",
            Self::Python => "Python-2.0.1",
            Self::Bsd2Clause => "BSD-2-Clause",
            Self::Lgpl21OrLater => "LGPL-2.1-or-later",
        }
    }

    /// Whether conveying this component obliges us to offer its source.
    pub fn is_copyleft(self) -> bool {
        matches!(
            self,
            Self::Gpl2OrLater | Self::Gpl3OrLater | Self::Lgpl21OrLater
        )
    }

    /// The full text, as committed under `licenses/`.
    pub fn text(self) -> &'static str {
        match self {
            Self::Gpl2OrLater => {
                include_str!("../../../licenses/GPL-2.0.txt")
            }
            Self::Gpl3OrLater => {
                include_str!("../../../licenses/GPL-3.0.txt")
            }
            Self::Bsd2ClausePatent => {
                include_str!("../../../licenses/BSD-2-Clause-Patent.txt")
            }
            Self::Bsd3Clause => {
                include_str!("../../../licenses/BSD-3-Clause-virtio-win.txt")
            }
            Self::OpenSsh => include_str!("../../../licenses/OpenSSH.txt"),
            Self::Apache2 => include_str!("../../../licenses/Apache-2.0.txt"),
            Self::Python => include_str!("../../../licenses/Python.txt"),
            Self::Bsd2Clause => {
                include_str!("../../../licenses/BSD-2-Clause-libarchive.txt")
            }
            Self::Lgpl21OrLater => {
                include_str!("../../../licenses/LGPL-2.1.txt")
            }
        }
    }
}

/// One third-party component the built image carries.
#[derive(Debug, Clone, Copy)]
pub struct Component {
    /// Upstream's name for it.
    pub name: &'static str,
    /// The exact version fetched, matching `tools/fetch-payload.sh`.
    pub version: &'static str,
    /// What it becomes on the media, so a reader can tie a notice to a file.
    pub carried_as: &'static str,
    pub license: License,
    pub copyright: &'static str,
    /// The project.
    pub upstream: &'static str,
    /// Corresponding source **for this version**, not for HEAD. GPLv3 §6 is about the
    /// source of the object code that was actually conveyed.
    pub source: &'static str,
}

