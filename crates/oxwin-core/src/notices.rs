/// The notices, without the license texts. What `oxwin licenses` prints.
///
/// Written rather than derived from the payload table in `assets`, because it has to say
/// something true in a build with no payload embedded: someone asking what the terms are
/// is asking about the tool, not about whether this particular checkout has run the
/// fetch script.
pub fn summary() -> String {
    let mut out = String::from(
        "oxwin is Copyright 2026 Oxide Computer Company and is licensed \
         MPL-2.0.\n\nThe images it builds carry third-party software, embedded \
         in this binary and\nwritten onto the media unmodified:\n",
    );
    for c in PAYLOAD {
        out += &format!(
            "\n  {} {}\n    {}\n    carried as: {}\n    {}\n    upstream:   {}\n    \
             source:     {}\n",
            c.name,
            c.version,
            c.license.spdx(),
            c.carried_as,
            c.copyright,
            c.upstream,
            c.source,
        );
    }
    out += "\nThe GPL- and LGPL'd components are conveyed unmodified: uefi-ntfs \
            and efifs as\nseparate UEFI executables run by firmware, mtools and \
            Elevate.exe as separate\nWindows executables installed by \
            cloudbase-init's MSI. None is linked into\nthis program. Their \
            complete corresponding source is at the URLs above, pinned\nto the \
            versions shipped.\n\nRun `oxwin licenses --full` for the license \
            texts, or see THIRD-PARTY.md.\n";
    out
}

/// The notices plus every license text, each printed once.
pub fn full() -> String {
    let mut out = summary();
    let mut done: Vec<&'static str> = Vec::new();
    for c in PAYLOAD {
        let spdx = c.license.spdx();
        if done.contains(&spdx) {
            continue;
        }
        done.push(spdx);
        out += &format!(
            "\n\n{}\n{spdx}\n{}\n\n{}",
            "=".repeat(76),
            "=".repeat(76),
            c.license.text()
        );
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The one real risk in this file: a version bumped in `fetch-payload.sh` and not
    /// here, so the notices name terms for a component nobody ships any more and the
    /// source URL points at the wrong tree.
    ///
    /// Reads the script rather than skipping when it is absent. This workspace is not
    /// published as a crate, so `tools/` is always two directories up; if that ever
    /// stops being true this should fail loudly rather than quietly prove nothing.
    #[test]
    fn every_pinned_version_is_accounted_for() {
        let script = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../tools/fetch-payload.sh");
        let text = std::fs::read_to_string(&script).unwrap_or_else(|e| {
            panic!("{}: {e} — the notices cannot be checked", script.display())
        });

        // Every version the fetch script pins, and the component that must carry it.
        let pins = [
            ("VIRTIO_VERSION", "virtio-win guest drivers"),
            ("OPENSSH_VERSION", "Win32-OpenSSH"),
            ("EFIFS_VERSION", "efifs"),
            ("UEFI_SHELL_VERSION", "UEFI-Shell"),
            ("UEFI_NTFS_VERSION", "uefi-ntfs"),
            ("CLOUDBASE_VERSION", "cloudbase-init"),
        ];
        for (var, name) in pins {
            let prefix = format!("{var}=");
            let value = text
                .lines()
                .find_map(|l| l.trim().strip_prefix(&prefix))
                .map(|v| v.trim().trim_matches('"').to_string())
                .unwrap_or_else(|| {
                    panic!("{var} is no longer set in fetch-payload.sh")
                });
            let component = PAYLOAD
                .iter()
                .find(|c| c.name == name)
                .unwrap_or_else(|| panic!("no notice names {name}"));
            assert_eq!(
                component.version, value,
                "fetch-payload.sh pins {name} at {value} but the notices say \
                 {} — bump the version, the source URL and THIRD-PARTY.md",
                component.version
            );
        }

        // Components carried inside another payload rather than fetched and pinned
        // independently by fetch-payload.sh: their version is a fact read off the
        // binary itself (see the comments on their `Component` entries), not a
        // script variable to cross-check.
        let bundled = [
            "CPython (bundled inside the cloudbase-init MSI)",
            "mtools (mlabel.exe, mcopy.exe, mdir.exe, bundled inside the cloudbase-init MSI)",
            "bsdtar (bundled inside the cloudbase-init MSI)",
            "Elevate.exe (bundled inside the cloudbase-init MSI, likely \
             jpassing/elevate)",
        ];

        // And nothing here is unpinned: a component in the notices that the script does
        // not fetch, and that no bundled entry accounts for, is a notice for something
        // we do not ship.
        assert_eq!(
            PAYLOAD.len(),
            pins.len() + bundled.len(),
            "the notices list {} components, fetch-payload.sh pins {}, and {} \
             are bundled rather than independently pinned",
            PAYLOAD.len(),
            pins.len(),
            bundled.len()
        );
    }

    /// Every license text is really present and really that license. `include_str!` of
    /// a wrong-but-existing file would otherwise ship the GPLv2 text for a GPLv3 work.
    #[test]
    fn every_license_text_is_the_license_it_claims() {
        for (license, marker) in [
            (License::Gpl2OrLater, "Version 2, June 1991"),
            (License::Gpl3OrLater, "Version 3, 29 June 2007"),
            (License::Bsd2ClausePatent, "BSD-2-Clause-Patent"),
            (License::Bsd3Clause, "Red Hat"),
            (License::OpenSsh, "part of the OpenSSH software"),
            (License::Apache2, "TERMS AND CONDITIONS FOR USE, REPRODUCTION"),
            (License::Python, "PYTHON SOFTWARE FOUNDATION LICENSE"),
            (License::Bsd2Clause, "libarchive distribution as a whole"),
            (License::Lgpl21OrLater, "GNU LESSER GENERAL PUBLIC LICENSE"),
        ] {
            let text = license.text();
            assert!(
                text.contains(marker),
                "the text for {} does not contain {marker:?}",
                license.spdx()
            );
        }
    }

    /// Apache-2.0 obliges us to convey the license and the NOTICE; the MSI also
    /// bundles a CPython runtime, which has its own terms. Conveying a
    /// component without its notice is the kind of thing that is only ever
    /// found by somebody auditing an artifact.
    #[test]
    fn cloudbase_init_and_its_python_are_both_named() {
        let text = summary();
        assert!(text.contains("cloudbase-init"), "{text}");
        assert!(text.contains("1.1.8"), "{text}");
        assert!(text.contains("Apache-2.0"), "{text}");
        assert!(text.to_lowercase().contains("python"), "{text}");
    }

    /// Every license named has to have a text committed under `licenses/`, or
    /// `--full` prints a heading with nothing under it.
    #[test]
    fn every_license_text_is_non_empty() {
        for c in PAYLOAD {
            assert!(
                c.license.text().len() > 100,
                "{} has no license text",
                c.name
            );
        }
    }
}
